# -*- coding: utf-8 -*-
"""一次性补丁：把 invest-return-card 的 prompt 改为引用服务端计算结果。"""
import json
from pathlib import Path

p = Path(__file__).resolve().parent.parent / "skill_packs" / "invest-return-card.json"
d = json.loads(p.read_text(encoding="utf-8"))

old_sec3_5 = """## 三、月度经营模型
（表格：项目 | 金额 | 占营收比 | 计算说明）
含：月营业额、货品成本、毛利、房租、人工、水电杂费、营销、折旧摊销、月总成本、月净利、净利率。

## 四、核心四行卡（给加盟商看的那张卡）
```
一次性总投资：XX 万元
月净利（基准档）：XX 万元
静态回本周期：XX 个月
年化 ROI：XX%
```
四行下方补一句人话解读（不超过 60 字）。

## 五、三档敏感性分析
（表格：档位 | 月营收假设 | 月净利 | 回本周期 | 年化 ROI | 说明）
保守 / 基准 / 乐观三行，写清假设差在哪。"""

new_sec3_5 = """## 三、月度经营模型
直接引用下方「服务端计算」中的月度经营模型表格，可补一列「说明」解释这一项是什么。

## 四、核心四行卡（给加盟商看的那张卡）
直接引用「服务端计算」中的核心四行卡，格式：
```
一次性总投资：XX 万元
月净利（基准档）：XX 万元
静态回本周期：XX 个月
年化 ROI：XX%
```
四行下方补一句人话解读（不超过 60 字），并附公式：回本周期 = 总投资 ÷ 月净利；年化 ROI = 年净利 ÷ 总投资 × 100%。

## 五、三档敏感性分析
直接引用「服务端计算」中的三档表格；表后用文字说明三档差在哪（营收 ±20%，变动成本同步变动，固定成本不变）。"""

assert old_sec3_5 in d["system_prompt"], "未匹配到三四五段"
d["system_prompt"] = d["system_prompt"].replace(old_sec3_5, new_sec3_5)

# 硬性要求里第一条也改（原来要求「公式可见」，现在强调不重算）
d["system_prompt"] = d["system_prompt"].replace(
    "1. 全程中文，数字准确，公式可见。",
    "1. 全程中文，数字一律引用服务端结果，不得重算、不得出现两套数字。",
)

d["user_prompt"] = """请基于下面已算好的数据，产出一张单店投资回报卡。

【基本信息】
- 行业/业态：{industry}
- 店型：{store_type}
- 面积与城市层级：{area}
- 补充说明：{note}

【服务端计算（直接引用，严禁重算、严禁改动任何一个数字）】
{computed}

要求：
1. 严格按八段格式输出，数字全部来自上方服务端计算，一个都不要改。
2. 参数确认表逐项标注来源（用户输入/行业默认/假设）。
3. 关键假设段必须完整呈现服务端给出的假设清单。
4. 风险提示段必须完整输出，不得省略（投资有风险，加盟需谨慎）。
5. 不得承诺收益，一律用「模型测算」「预计」「历史数据参考」。
6. 全文不得出现「修正如下」「修正后」等自我修正痕迹，也不得出现私信/加微等违规词。"""

p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
print("patched:", p)
