/**
 * 对话页的「会话命令」：客户在输入框里直接打出来就要生效的整句指令。
 *
 * 2026-09-17 现场缺陷（用户：「既不能重新开始 也不能正确识别复盘文件」）：
 * 视频复盘只把「重新开始」当成**当前这一轮的答案**，于是回一句「先别急——我还没拿到你的数据」，
 * 反复打也出不去（对话页的「再问一次 / 重新开始」按钮只在交付完成后才渲染）。
 *
 * 口径：
 * - 只认**整行**命令，前后允许标点/空格；句子里还有别的内容（例如「重新开始写文案」）一律当正常回答，
 *   不能劫持客户本来想说的话。
 * - 这里不判断能力是否支持重开，只回答「这句话是不是重开命令」；
 *   真正的重置（记录、填写内容、附件、本机留存）由对话页执行。
 */
export const RESTART_COMMAND_PATTERN =
  /^(?:请?重新开始|重新开始吧|重来|重新来|重开|重新填|重新填写|重新做|清空重来|从头开始|再来一次|再来一遍)[。！!~～\s]*$/;

/** 输入是否是一条「重新开始」命令。 */
export function isRestartCommand(value: string): boolean {
  return RESTART_COMMAND_PATTERN.test((value ?? "").trim());
}
